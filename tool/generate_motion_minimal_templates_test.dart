// Run: flutter test tool/generate_motion_minimal_templates_test.dart
// This development-only generator uses the SDK formatter, never a browser dependency.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:nib_ember_living/docs/doc_example_catalog.dart';

import 'motion_minimal_template_source.dart';

void main() {
  test('regenerate formatted motion source templates', () async {
    final folder = Directory('.dart_tool/motion_template_format');
    folder.createSync(recursive: true);
    const families = [
      'entrance',
      'bookmark',
      'water',
      'tuner',
      'shared-layout',
      'spring',
      'compare',
      'draw-follow',
      'counter',
      'progress',
      'linked',
      'pivot',
      'selection',
      'expand',
      'accordion',
      'tab',
      'snap',
      'tween',
      'transform',
      'hover',
      'drag',
      'pinch',
      'swipe',
      'flip',
      'preset',
      'loop',
      'keyframes',
      'presence',
      'layout',
      'stagger',
      'variants',
      'viewport',
      'accessibility',
      'path',
      'draw',
      'navigation',
      'glass',
      'validation',
      'controller',
      'timeline',
      'values',
      'physics',
      'scroll',
      'parallax',
      'route',
      'text',
    ];
    final cases = <String, (String, String)>{
      for (final family in families) '$family|': (family, ''),
      for (final example in textMotionExamples.values)
        'text|${example.constructorArguments}': (
          'text',
          example.constructorArguments,
        ),
    };
    var index = 0;
    for (final entry in cases.entries) {
      final (family, arguments) = entry.value;
      File('${folder.path}/${index++}.dart').writeAsStringSync(
        motionTemplateSource(
          family,
          arguments: arguments,
          distance: 12345.625,
          durationMs: 98765,
          stiffness: 45678.625,
          damping: 34567.625,
          mass: 23456.625,
        ),
      );
    }
    final flutterRoot =
        Platform.environment['FLUTTER_ROOT'] ?? '/home/occ/DevTools/flutter';
    final formatted = await Process.run('$flutterRoot/bin/dart', [
      'format',
      '--line-length',
      '78',
      folder.path,
    ]);
    expect(
      formatted.exitCode,
      0,
      reason: '${formatted.stdout}\n${formatted.stderr}',
    );
    final output = StringBuffer(
      '// Generated by tool/generate_motion_minimal_templates_test.dart.\n// Edit the authoring input and regenerate; preserve the formatted code literals.\nconst motionMinimalTemplates = <String, String>{\n',
    );
    index = 0;
    for (final key in cases.keys) {
      final source = File('${folder.path}/${index++}.dart')
          .readAsStringSync()
          .replaceAll('12345.625', '@@distance@@')
          .replaceAll('12346', '@@distanceRound@@')
          .replaceAll('${12345.625 / 360}', '@@distanceTurn@@')
          .replaceAll('98765', '@@duration@@')
          .replaceAll('45678.625', '@@stiffness@@')
          .replaceAll('34567.625', '@@damping@@')
          .replaceAll('23456.625', '@@mass@@');
      output.writeln("  '$key': r'''$source''',");
    }
    output.writeln('};');
    File('lib/docs/motion_minimal_templates.dart')
        .writeAsStringSync(output.toString());
    folder.deleteSync(recursive: true);
  });
}
